'use strict';

const fs = require('node:fs');
const path = require('node:path');

const STIGNORE_PATTERNS = [
  '# josh per-host artifacts (do not sync)',
  '*.capacity.json',
  '# locks (per-host claim primitives)',
  'locks/',
  'orchestrator/orchestrator.lock',
  '# ephemeral/atomic write tempfiles',
  '*.tmp',
  '*.tmp.*',
  '# stop-flag for the A2A bridge',
  'a2a/.stop',
  '# pause/drain markers (per-host)',
  'orchestrator/.paused',
  'orchestrator/.draining',
];

function stignorePath(joshRoot) {
  return path.join(joshRoot, '.stignore');
}

const BEGIN_MARKER = '# >>> josh managed — regenerated by `josh sync stignore` >>>';
const END_MARKER = '# <<< josh managed <<<';

// `.stignore` is a file the operator also edits - it is the only place to exclude
// a local cache, a scratch directory or large media from syncing across the
// fleet. Rewriting the whole file discarded those lines silently, and the
// consequence lands off-box: whatever they had excluded starts replicating to
// every other machine.
//
// The recommended patterns now live in a delimited block that is replaced in
// place; anything outside it is kept. A file written before this change has no
// markers, so its contents are preserved below the block.
function managedBlock() {
  return [BEGIN_MARKER, ...STIGNORE_PATTERNS, END_MARKER].join('\n');
}

function writeStignore(joshRoot) {
  const p = stignorePath(joshRoot);
  fs.mkdirSync(path.dirname(p), { recursive: true });

  let existing = '';
  try { existing = fs.readFileSync(p, 'utf8'); } catch (e) { /* first write */ }

  let out;
  const begin = existing.indexOf(BEGIN_MARKER);
  const end = existing.indexOf(END_MARKER);
  if (begin !== -1 && end !== -1 && end > begin) {
    out = existing.slice(0, begin) + managedBlock() + existing.slice(end + END_MARKER.length);
  } else if (existing.trim()) {
    out = `${managedBlock()}\n\n${existing.replace(/^\n+/, '')}`;
  } else {
    out = `${managedBlock()}\n`;
  }
  if (!out.endsWith('\n')) out += '\n';

  fs.writeFileSync(p, out);
  return p;
}

function readStignore(joshRoot) {
  const p = stignorePath(joshRoot);
  if (!fs.existsSync(p)) return null;
  return fs.readFileSync(p, 'utf8');
}

module.exports = {
  STIGNORE_PATTERNS,
  writeStignore,
  readStignore,
  stignorePath,
  BEGIN_MARKER,
  END_MARKER,
};
